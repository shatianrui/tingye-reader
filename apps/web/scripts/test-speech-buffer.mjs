import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import ts from 'typescript';
await mkdir('.sites-runtime',{recursive:true});
await writeFile('.sites-runtime/speech-buffer-test.mjs',ts.transpileModule(await readFile('lib/speech-buffer.ts','utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText);
const {SpeechBuffer}=await import('../.sites-runtime/speech-buffer-test.mjs');
const tick=()=>new Promise(r=>setTimeout(r,0));
const calls=[];
const buffer=new SpeechBuffer((text,signal)=>new Promise((resolve,reject)=>{
  calls.push({text,resolve,reject,signal});
  signal.addEventListener('abort',()=>reject(new DOMException('aborted','AbortError')),{once:true});
}));
buffer.prepare(['one','two','three','four','five']);
const first=buffer.get('one');
assert.equal(calls.length,2,'Maximum two concurrent requests');
assert.equal(buffer.get('one'),first,'Current and speculative requests must deduplicate');
calls[0].resolve(new Blob(['one']));await first;await tick();
assert.deepEqual(calls.map(c=>c.text),['one','two','three']);
buffer.prepare(['one','two','three','four','five'],true);
calls[1].resolve(new Blob(['two']));calls[2].resolve(new Blob(['three']));await tick();
assert.equal(calls.length,3,'Pause must stop starting speculative requests');
assert.equal(buffer.ready(['two','three']),2);
assert.equal((await buffer.get('two')).size,3);assert.equal(calls.length,3,'Cache hit must avoid network');
buffer.prepare(['one','two','three','four','five']);
assert.equal(calls.length,5);
buffer.prepare(['new location','new next']);await tick();
assert.ok(calls[3].signal.aborted&&calls[4].signal.aborted,'Seek aborts old work');
assert.equal(buffer.ready(['two','three']),0,'Seek evicts stale audio');
const demanded=buffer.get('new location');
calls.find(c=>c.text==='new location').resolve(new Blob(['new']));await demanded;await tick();
calls.find(c=>c.text==='new next').reject(new Error('temporary failure'));await tick();
const retry=buffer.get('new next');
assert.equal(calls.filter(c=>c.text==='new next').length,2,'Speculative failure retries only on demand');
calls.at(-1).resolve(new Blob(['retry']));await retry;await tick();
buffer.prepare(Array.from({length:30},(_,i)=>'bounded-'+i));
assert.equal(buffer.entries.size,7,'Lookahead must be bounded');
const pending=buffer.get('bounded-0');buffer.clear();await assert.rejects(pending,{name:'AbortError'});await tick();
assert.equal(buffer.entries.size,0);assert.equal(buffer.running,0);
console.log('PASS: bounded concurrency, deduplication, cache reuse, pause/resume, seek cancellation, retry, cleanup.');
